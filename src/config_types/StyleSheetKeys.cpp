const char *styleSheetKeyName(int32_t keyHash)
{
    static const std::unordered_map<int32_t, const char *> kByHash = [] {
        std::unordered_map<int32_t, const char *> byHash;
        byHash.reserve(kStyleSheetKeyNames.size());
        for (const char *name : kStyleSheetKeyNames)
        {
            byHash.emplace(styleSheetKeyHash(name), name);
        }
        return byHash;
    }();
    const auto it = kByHash.find(keyHash);
    return it == kByHash.end() ? nullptr : it->second;
}

size_t styleSheetKnownKeyCount()
{
    return kStyleSheetKeyNames.size();
}
